-- =========================================================
-- 1. EXTENSIONS
-- =========================================================

create extension if not exists pgcrypto;


-- =========================================================
-- 2. SENSOR LOGS TABLE
-- =========================================================

create table if not exists public.sensor_logs (

    -- Primary key
    id bigint generated by default as identity primary key,

    -- Time of sensor reading
    created_at timestamptz not null default now(),

    -- Device identification
    device_id text not null default 'ESP32-01',

    -- DHT11
    temperature double precision,
    humidity double precision,

    -- Soil moisture
    soil_moisture integer,

    -- Ultrasonic water-level measurement
    water_level double precision,

    -- MPU6050 seismic/vibration value
    seismic double precision,

    -- MQ sensor
    air_quality double precision,

    -- Rain sensor
    rain_level double precision,

    -- Barometric & Altitude (BMP280)
    baro_pressure double precision,
    altitude double precision,

    -- Wind telemetry
    wind_speed double precision,
    wind_direction double precision,

    -- GPS Coordinates (NEO-6M)
    latitude double precision,
    longitude double precision,

    -- System status
    status text not null default 'Updated',

    -- Priority
    priority_level integer not null default 3,

    -- Optional notes
    message text
);


-- =========================================================
-- 3. CONSTRAINTS
-- =========================================================

alter table public.sensor_logs
drop constraint if exists sensor_logs_temperature_check;

alter table public.sensor_logs
add constraint sensor_logs_temperature_check
check (
    temperature is null
    or temperature between -50 and 100
);


alter table public.sensor_logs
drop constraint if exists sensor_logs_humidity_check;

alter table public.sensor_logs
add constraint sensor_logs_humidity_check
check (
    humidity is null
    or humidity between 0 and 100
);


alter table public.sensor_logs
drop constraint if exists sensor_logs_priority_check;

alter table public.sensor_logs
add constraint sensor_logs_priority_check
check (
    priority_level between 1 and 3
);


-- =========================================================
-- 4. INDEXES
-- =========================================================

create index if not exists
sensor_logs_created_at_idx
on public.sensor_logs (created_at desc);


create index if not exists
sensor_logs_device_id_idx
on public.sensor_logs (device_id);


create index if not exists
sensor_logs_priority_idx
on public.sensor_logs (priority_level);


create index if not exists
sensor_logs_status_idx
on public.sensor_logs (status);


-- =========================================================
-- 5. ENABLE ROW LEVEL SECURITY
-- =========================================================

alter table public.sensor_logs
enable row level security;


-- =========================================================
-- 6. REMOVE OLD POLICIES
-- =========================================================

drop policy if exists
"Allow anonymous sensor inserts"
on public.sensor_logs;


drop policy if exists
"Allow anonymous sensor reads"
on public.sensor_logs;


drop policy if exists
"Allow authenticated sensor reads"
on public.sensor_logs;


-- =========================================================
-- 7. ESP32 INSERT POLICY
-- =========================================================
-- Allows the ESP32 using the Supabase publishable/anon key
-- to insert sensor readings.

create policy
"Allow anonymous sensor inserts"
on public.sensor_logs
for insert
to anon
with check (
    true
);


-- =========================================================
-- 8. PUBLIC READ POLICY
-- =========================================================
-- Allows your dashboard to read sensor data when using
-- the anon/publishable key.

create policy
"Allow anonymous sensor reads"
on public.sensor_logs
for select
to anon
using (
    true
);


-- =========================================================
-- 9. AUTHENTICATED READ POLICY
-- =========================================================

create policy
"Allow authenticated sensor reads"
on public.sensor_logs
for select
to authenticated
using (
    true
);


-- =========================================================
-- 10. LATEST SENSOR READING VIEW
-- =========================================================

create or replace view public.latest_sensor_reading
with (security_invoker = true)
as
select
    id,
    created_at,
    device_id,
    temperature,
    humidity,
    soil_moisture,
    water_level,
    seismic,
    air_quality,
    rain_level,
    baro_pressure,
    altitude,
    wind_speed,
    wind_direction,
    latitude,
    longitude,
    status,
    priority_level,
    message
from public.sensor_logs
order by created_at desc
limit 1;


-- =========================================================
-- 11. LATEST READING FOR EACH DEVICE
-- =========================================================

create or replace view public.latest_device_readings
with (security_invoker = true)
as
select distinct on (device_id)
    id,
    created_at,
    device_id,
    temperature,
    humidity,
    soil_moisture,
    water_level,
    seismic,
    air_quality,
    rain_level,
    baro_pressure,
    altitude,
    wind_speed,
    wind_direction,
    latitude,
    longitude,
    status,
    priority_level,
    message
from public.sensor_logs
order by
    device_id,
    created_at desc;


-- =========================================================
-- 12. SENSOR STATISTICS VIEW
-- =========================================================

create or replace view public.sensor_statistics
with (security_invoker = true)
as
select

    count(*) as total_readings,

    round(
        avg(temperature)::numeric,
        2
    ) as avg_temperature,

    round(
        avg(humidity)::numeric,
        2
    ) as avg_humidity,

    round(
        avg(soil_moisture)::numeric,
        2
    ) as avg_soil_moisture,

    round(
        avg(water_level)::numeric,
        2
    ) as avg_water_level,

    round(
        avg(seismic)::numeric,
        2
    ) as avg_seismic,

    round(
        avg(air_quality)::numeric,
        2
    ) as avg_air_quality,

    round(
        avg(rain_level)::numeric,
        2
    ) as avg_rain_level,

    count(*) filter (
        where priority_level = 1
    ) as critical_alerts,

    count(*) filter (
        where priority_level = 2
    ) as warning_alerts,

    count(*) filter (
        where priority_level = 3
    ) as normal_readings

from public.sensor_logs;


-- =========================================================
-- 13. RECENT ALERTS VIEW
-- =========================================================

create or replace view public.recent_alerts
with (security_invoker = true)
as
select
    id,
    created_at,
    device_id,
    temperature,
    humidity,
    soil_moisture,
    water_level,
    seismic,
    air_quality,
    rain_level,
    baro_pressure,
    altitude,
    wind_speed,
    wind_direction,
    latitude,
    longitude,
    status,
    priority_level,
    message
from public.sensor_logs
where priority_level < 3
order by created_at desc
limit 100;


-- =========================================================
-- 14. ENABLE REALTIME
-- =========================================================
-- Allows your dashboard to receive new ESP32 readings
-- without refreshing the page.

do $$
begin

    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
        and schemaname = 'public'
        and tablename = 'sensor_logs'
    ) then

        alter publication supabase_realtime
        add table public.sensor_logs;

    end if;

end $$;


